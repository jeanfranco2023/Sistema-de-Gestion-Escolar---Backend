CREATE TABLE IF NOT EXISTS auditoria_accesos_api (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id VARCHAR(36) NOT NULL,
    usuario_id BIGINT,
    usuario_nombre VARCHAR(100) NOT NULL,
    roles VARCHAR(300) NOT NULL,
    metodo VARCHAR(10) NOT NULL,
    ruta VARCHAR(500) NOT NULL,
    estado_http INTEGER NOT NULL,
    direccion_ip VARCHAR(45),
    agente_usuario VARCHAR(300),
    duracion_ms BIGINT NOT NULL,
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auditoria_accesos_solicitud UNIQUE (solicitud_id)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_accesos_fecha ON auditoria_accesos_api (fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_accesos_usuario_fecha ON auditoria_accesos_api (usuario_id, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_accesos_estado_fecha ON auditoria_accesos_api (estado_http, fecha_evento DESC);

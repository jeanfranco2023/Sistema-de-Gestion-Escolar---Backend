CREATE TABLE historial_estados_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL,
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL,
    usuario_id BIGINT NOT NULL,
    nombre_usuario_snapshot VARCHAR(30) NOT NULL,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion_gestion VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_historial_incidencia
        FOREIGN KEY (incidencia_id) REFERENCES incidencias_conductuales (id) ON DELETE RESTRICT,
    CONSTRAINT fk_historial_incidencia_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT chk_historial_incidencia_estado_anterior
        CHECK (estado_anterior IS NULL OR estado_anterior IN ('ABIERTA', 'ATENDIDA', 'CERRADA')),
    CONSTRAINT chk_historial_incidencia_estado_nuevo
        CHECK (estado_nuevo IN ('ABIERTA', 'ATENDIDA', 'CERRADA')),
    CONSTRAINT chk_historial_incidencia_transicion
        CHECK (estado_anterior IS NULL OR estado_anterior <> estado_nuevo),
    CONSTRAINT chk_historial_incidencia_observacion
        CHECK (length(btrim(observacion_gestion)) > 0)
);

CREATE INDEX idx_historial_incidencia_fecha
    ON historial_estados_incidencia (incidencia_id, fecha_cambio, id);

CREATE FUNCTION fn_proteger_historial_estados_incidencia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'El historial de estados de incidencias es inmutable';
END;
$$;

CREATE TRIGGER trg_historial_estados_incidencia_inmutable
BEFORE UPDATE OR DELETE ON historial_estados_incidencia
FOR EACH ROW EXECUTE FUNCTION fn_proteger_historial_estados_incidencia();
